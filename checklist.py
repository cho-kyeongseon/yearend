def match_item(text: str) -> str | None:
    """질문에서 가장 잘 맞는 체크리스트 항목 키. 없으면 None."""
    scores = {k: sum(w for word in words if word in text) for k, (words, w) in KEYWORDS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] > 0 else None


def item_refs(key: str) -> list:
    """항목의 '공제 가능' 결과들에 달린 근거 쪽 (중복 제거)."""
    refs = []
    for n in ITEMS[key]["nodes"].values():
        if n.get("result") == "ok":
            refs += [r for r in n["refs"] if r not in refs]
    return refs


